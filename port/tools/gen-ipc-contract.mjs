#!/usr/bin/env node
// Generates port/src/shared/ipc-contract.ts and port/src/preload/bridge.generated.ts
// from artifacts/manifests/ipc-channels.json (machine-extracted from the shipped
// Videoclaw 0.0.40 bundles, see docs/04-ipc-contract.md) plus the hand-curated,
// evidence-cited tools/ipc-verified-shapes.json. NEVER hand-edit the outputs.
// Usage: node port/tools/gen-ipc-contract.mjs   (from repo root or port/)
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const portRoot = resolve(here, "..");
const repoRoot = resolve(portRoot, "..");
const channels = JSON.parse(readFileSync(join(repoRoot, "artifacts/manifests/ipc-channels.json"), "utf8"));
const verified = JSON.parse(readFileSync(join(here, "ipc-verified-shapes.json"), "utf8"));

const ident = (ch) => ch.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "");
const cite = (o) => {
  const out = [];
  for (const [kind, line, sig] of o.handlers) out.push(`main/index.js L${line} ipcMain.${kind}: ${sig}`);
  for (const [line, payload] of o.sends) out.push(`main/index.js L${line} sendToRenderer payload: ${payload || "(none)"}`);
  for (const d of o.delegates ?? []) if (d.calls?.length) out.push(`delegates to ${d.calls.join(", ")}`);
  return out.map((s) => s.replace(/\*\//g, "*\\/"));
};
const params = (argStr) => argStr.split(",").map((s) => s.trim()).filter(Boolean);

const invoke = [], send = [], push = [], local = [];
for (const o of channels) {
  const b = o.bridge[0];
  if (!b) { local.push(o); continue; }
  const kind = b[2];
  (kind === "invoke" ? invoke : kind === "send" ? send : push).push(o);
}

const stats = { invoke: invoke.length, send: send.length, push: push.length, unused: local.length,
  argsNamed: 0, argsVerified: 0, argsPlaceholder: 0,
  resultVerified: 0, resultFull: 0, resultPartial: 0, resultPlaceholder: 0,
  pushVerified: 0, pushFull: 0, pushPartial: 0, pushPlaceholder: 0, sendVoid: 0, sharedTypes: 0 };
const known = new Set(channels.map((o) => o.channel));
for (const sect of ["result", "push", "args"]) for (const ch of Object.keys(verified[sect] ?? {})) {
  if (!known.has(ch)) throw new Error(`ipc-verified-shapes.json ${sect}: unknown channel ${ch}`);
}
const lvl = (v, kind) => { stats[kind + (v.level === "full" ? "Full" : "Partial")]++; };
const L = [];
const P = (s = "") => L.push(s);
P("// AUTO-GENERATED by port/tools/gen-ipc-contract.mjs — DO NOT EDIT.");
P("// Source: artifacts/manifests/ipc-channels.json (+ port/tools/ipc-verified-shapes.json).");
P("// Fidelity rule: every channel string and parameter NAME below was read from the shipped");
P("// Videoclaw 0.0.40 preload/main bundles. Parameter/result TYPES are `unknown` placeholders");
P("// unless a shape was proven from code (see `Verified*` comments with evidence lines).");
P("/* eslint-disable */");
P();
P("/** All 184 channel constants, verbatim from `const IPC = {…}` in out/main/index.js (L354). */");
P("export const IPC = {");
for (const o of channels) P(`  ${o.key}: ${JSON.stringify(o.channel)},`);
P("} as const;");
P("export type IpcKey = keyof typeof IPC;");
P("export type IpcChannel = (typeof IPC)[IpcKey];");
P();
P("// ───────────────────────── shared verified types ─────────────────────────");
for (const [name, v] of Object.entries(verified.shared ?? {})) {
  P(`/** Verified (${v.level}): ${v.evidence.replace(/\*\//g, "*\\/")} */`);
  P(`export type ${name} = ${v.type};`);
  stats.sharedTypes++;
}
P();
P("// ───────────────────────── placeholder & verified types ─────────────────────────");
const argType = (o, name) => `Unknown_${ident(o.channel)}__${name}`;
const resType = (o) => `Unknown_${ident(o.channel)}__result`;
const payType = (o) => `Unknown_${ident(o.channel)}__payload`;
const emitArgs = (o, args) => {
  const ov = verified.args?.[o.channel] ?? {};
  for (const k of Object.keys(ov)) if (!params(args).includes(k)) throw new Error(`args override ${o.channel}.${k}: no such preload param`);
  for (const a of params(args)) {
    stats.argsNamed++;
    const v = ov[a];
    if (v) { P(`/** Verified (${v.level}): ${v.evidence} */`); P(`export type ${argType(o, a)} = ${v.type};`); stats.argsVerified++; }
    else { P(`export type ${argType(o, a)} = unknown; // TODO: payload not yet recovered — param \`${a}\` of preload ${o.bridge[0][0]}()`); stats.argsPlaceholder++; }
  }
};
for (const o of invoke) {
  const [, args] = o.bridge[0];
  emitArgs(o, args);
  const v = verified.result?.[o.channel];
  if (v) { P(`/** Verified (${v.level}): ${v.evidence} */`); P(`export type ${resType(o)} = ${v.type};`); stats.resultVerified++; lvl(v, "result"); }
  else { P(`export type ${resType(o)} = unknown; // TODO: payload not yet recovered — see ${cite(o)[0] ?? "n/a"}`); stats.resultPlaceholder++; }
}
for (const o of send) {
  const [, args] = o.bridge[0];
  emitArgs(o, args);
  stats.sendVoid++;
}
for (const o of push) {
  const v = verified.push?.[o.channel];
  if (v) { P(`/** Verified (${v.level}): ${v.evidence} */`); P(`export type ${payType(o)} = ${v.type};`); stats.pushVerified++; lvl(v, "push"); }
  else { P(`export type ${payType(o)} = unknown; // TODO: payload not yet recovered — see ${cite(o)[0] ?? "n/a"}`); stats.pushPlaceholder++; }
}
P();
P("// ───────────────────────── renderer → main: invoke ↔ ipcMain.handle (" + invoke.length + ") ─────────────────────────");
P("export interface IpcInvokeContract {");
for (const o of invoke) {
  const [m, args] = o.bridge[0];
  P("  /**");
  for (const c of cite(o)) P(`   * ${c}`);
  P("   */");
  P(`  ${JSON.stringify(o.channel)}: { key: ${JSON.stringify(o.key)}; method: ${JSON.stringify(m)}; args: [${params(args).map((a) => `${a}: ${argType(o, a)}`).join(", ")}]; result: ${resType(o)} };`);
}
P("}");
P();
P("// ───────────────────────── renderer → main: send ↔ ipcMain.on (" + send.length + ", no response) ─────────────────────────");
P("export interface IpcSendContract {");
for (const o of send) {
  const [m, args] = o.bridge[0];
  P("  /**"); for (const c of cite(o)) P(`   * ${c}`); P("   */");
  P(`  ${JSON.stringify(o.channel)}: { key: ${JSON.stringify(o.key)}; method: ${JSON.stringify(m)}; args: [${params(args).map((a) => `${a}: ${argType(o, a)}`).join(", ")}] };`);
}
P("}");
P();
P("// ───────────────────────── main → renderer: webContents.send ↔ ipcRenderer.on (" + push.length + ") ─────────────────────────");
P("/** Preload `subscribe()` forwards only the FIRST argument (payload) to the callback (preload L830). */");
P("export interface IpcPushContract {");
for (const o of push) {
  const [m] = o.bridge[0];
  P("  /**"); for (const c of cite(o)) P(`   * ${c}`); P("   */");
  P(`  ${JSON.stringify(o.channel)}: { key: ${JSON.stringify(o.key)}; method: ${JSON.stringify(m)}; payload: ${payType(o)} };`);
}
P("}");
P();
P("export type InvokeChannel = keyof IpcInvokeContract;");
P("export type SendChannel = keyof IpcSendContract;");
P("export type PushChannel = keyof IpcPushContract;");
P(`export const INVOKE_CHANNELS = ${JSON.stringify(invoke.map((o) => o.channel), null, 2)} as const satisfies readonly InvokeChannel[];`);
P(`export const SEND_CHANNELS = ${JSON.stringify(send.map((o) => o.channel))} as const satisfies readonly SendChannel[];`);
P(`export const PUSH_CHANNELS = ${JSON.stringify(push.map((o) => o.channel), null, 2)} as const satisfies readonly PushChannel[];`);
P(`/** Defined in main's IPC table but never used: preload implements pathForFile locally via webUtils. */`);
P(`export const UNUSED_CHANNELS = ${JSON.stringify(local.map((o) => o.channel))} as const;`);
P(`/** method name → channel, for every invoke channel (used by the main-process router). */`);
P(`export const INVOKE_METHOD_BY_CHANNEL = {`);
for (const o of invoke) P(`  ${JSON.stringify(o.channel)}: ${JSON.stringify(o.bridge[0][0])},`);
P(`} as const satisfies { [C in InvokeChannel]: IpcInvokeContract[C]["method"] };`);
P(`export const SEND_METHOD_BY_CHANNEL = {`);
for (const o of send) P(`  ${JSON.stringify(o.channel)}: ${JSON.stringify(o.bridge[0][0])},`);
P(`} as const satisfies { [C in SendChannel]: IpcSendContract[C]["method"] };`);
P();
P("// ───────────────────────── window.videoclaw (184 methods: 183 IPC + pathForFile) ─────────────────────────");
P("type Args<C extends InvokeChannel> = IpcInvokeContract[C][\"args\"];");
P("type Res<C extends InvokeChannel> = IpcInvokeContract[C][\"result\"];");
P("type SArgs<C extends SendChannel> = IpcSendContract[C][\"args\"];");
P("type Pay<C extends PushChannel> = IpcPushContract[C][\"payload\"];");
P("export interface VideoclawBridge {");
// keep the ORIGINAL member order of the preload bridge object
const order = JSON.parse(readFileSync(join(here, "bridge-order.json"), "utf8"));
const byMethod = new Map();
for (const o of channels) for (const [m, , k] of o.bridge) byMethod.set(m, { o, k });
let count = 0;
for (const m of order) {
  count++;
  if (m === "pathForFile") { P("  /** Local, not IPC: `webUtils.getPathForFile(file)` (preload L917). */"); P("  pathForFile(file: File): string;"); continue; }
  const { o, k } = byMethod.get(m);
  const ch = JSON.stringify(o.channel);
  const names = params(o.bridge[0][1]);
  if (k === "invoke") P(`  ${m}(...args: Args<${ch}>): Promise<Res<${ch}>>; // ${names.join(", ") || "()"}`);
  else if (k === "send") P(`  ${m}(...args: SArgs<${ch}>): void; // ipcRenderer.send`);
  else P(`  ${m}(cb: (payload: Pay<${ch}>) => void): () => void; // subscribe`);
}
P("}");
P(`export const BRIDGE_METHOD_COUNT = ${count};`);
P();
P("declare global {");
P("  interface Window { videoclaw: VideoclawBridge }");
P("}");
P();
P(`/** Coverage stats emitted by the generator. */`);
P(`export const CONTRACT_STATS = ${JSON.stringify(stats)} as const;`);
mkdirSync(join(portRoot, "src/shared"), { recursive: true });
writeFileSync(join(portRoot, "src/shared/ipc-contract.ts"), L.join("\n") + "\n");

// ── preload bridge (mirrors the original `bridge` object member-for-member) ──
const B = [];
B.push("// AUTO-GENERATED by port/tools/gen-ipc-contract.mjs — DO NOT EDIT.");
B.push("// Mirrors `const bridge = {…}` in out/preload/index.mjs (L835-1057), same member order.");
B.push('import { ipcRenderer, webUtils } from "electron";');
B.push('import { IPC, type VideoclawBridge } from "../shared/ipc-contract";');
B.push("");
B.push("function subscribe(channel: string, cb: (payload: any) => void): () => void {");
B.push("  const listener = (_e: unknown, payload: unknown) => cb(payload);");
B.push("  ipcRenderer.on(channel, listener);");
B.push("  return () => ipcRenderer.removeListener(channel, listener);");
B.push("}");
B.push("");
B.push("export const bridge: VideoclawBridge = {");
for (const m of order) {
  if (m === "pathForFile") { B.push("  pathForFile: (file: File) => webUtils.getPathForFile(file),"); continue; }
  const { o, k } = byMethod.get(m);
  const names = params(o.bridge[0][1]);
  const sig = names.map((n) => `${n}: any`).join(", ");
  const pass = names.length ? ", " + names.join(", ") : "";
  if (k === "invoke") B.push(`  ${m}: (${sig}) => ipcRenderer.invoke(IPC.${o.key}${pass}),`);
  else if (k === "send") B.push(`  ${m}: (${sig}) => ipcRenderer.send(IPC.${o.key}${pass}),`);
  else B.push(`  ${m}: (cb: any) => subscribe(IPC.${o.key}, cb),`);
}
B.push("};");
writeFileSync(join(portRoot, "src/preload/bridge.generated.ts"), B.join("\n") + "\n");
console.log(JSON.stringify(stats));
