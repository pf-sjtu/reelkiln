// docs/31: extracts the shipped descriptions of the paid-plane studio tools (makeStudioToolset L48906-49298) from
// the reconstructed main bundle (reference, never edited) into src/main/studio/studio-paid-tools.generated.ts.
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../../app/reconstructed/main/index.js", import.meta.url), "utf8");
const lines = src.split("\n");
const names = ["search_models", "call_model", "get_project_budget", "set_video_budget"];
const out = [];
for (const name of names) {
  const re = new RegExp(`studioTool\\(\\s*"${name}",\\s*`, "g");
  const m = re.exec(src);
  if (!m) throw new Error(`no studioTool ${name}`);
  let i = m.index + m[0].length;
  const q = src[i];
  let j = i + 1;
  while (src[j] !== q) { if (src[j] === "\\") j++; if (q === "`" && src[j] === "$" && src[j + 1] === "{") throw new Error("template expr"); j++; }
  const literal = src.slice(i, j + 1);
  const value = Function(`return ${literal}`)();
  const line = src.slice(0, m.index).split("\n").length;
  out.push(`/** ${name} — main/index.js L${line} (verbatim) */\nexport const ${name.toUpperCase()}_DESCRIPTION = ${JSON.stringify(value)};`);
}
writeFileSync(new URL("../src/main/studio/studio-paid-tools.generated.ts", import.meta.url), `// GENERATED by tools/gen-studio-paid-tools.mjs — do not edit.\n${out.join("\n")}\n`);
console.log("studio-paid-tools.generated.ts:", names.length, "descriptions", lines.length > 0 ? "ok" : "");
